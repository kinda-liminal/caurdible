// Convert a TrueType font to a VLW smooth font as a C header for M5GFX.
//
// Usage:
//   swift tools/make_vlw_font.swift <font.ttf> <pixel size> <symbol> <out.h>
//
// The glyph set is ASCII, Latin-1, and the punctuation and arrows the UI uses.
// CoreText renders each glyph as 8-bit coverage at an integer baseline.
// A mild gamma makes thin strokes hold up on the TFT.

import CoreGraphics
import CoreText
import Foundation

let args = CommandLine.arguments
guard args.count == 5, let pixelSize = Double(args[2]) else {
  FileHandle.standardError.write("usage: make_vlw_font.swift <font.ttf> <pixel size> <symbol> <out.h>\n".data(using: .utf8)!)
  exit(2)
}
let fontPath = args[1]
let symbol = args[3]
let outPath = args[4]
let gamma = 0.8

guard let provider = CGDataProvider(url: URL(fileURLWithPath: fontPath) as CFURL),
      let cgFont = CGFont(provider) else {
  FileHandle.standardError.write("cannot read \(fontPath)\n".data(using: .utf8)!)
  exit(1)
}
let font = CTFontCreateWithGraphicsFont(cgFont, CGFloat(pixelSize), nil, nil)

let extras: [UInt32] = [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026,
                        0x2039, 0x203A, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212]
let codepoints: [UInt32] = Array(0x20...0x7E) + Array(0xA0...0xFF) + extras

struct Glyph {
  var unicode: UInt32
  var width: Int
  var height: Int
  var advance: Int
  var top: Int
  var left: Int
  var bitmap: [UInt8]
}

var glyphs: [Glyph] = []
var missing: [String] = []
for cp in codepoints {
  var ch = UniChar(cp)
  var glyph: CGGlyph = 0
  guard CTFontGetGlyphsForCharacters(font, &ch, &glyph, 1), glyph != 0 else {
    missing.append(String(format: "U+%04X", cp))
    continue
  }
  var advance = CGSize.zero
  CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)
  let rect = CTFontGetBoundingRectsForGlyphs(font, .horizontal, &glyph, nil, 1)
  let x0 = Int(floor(rect.minX)), x1 = Int(ceil(rect.maxX))
  let y0 = Int(floor(rect.minY)), y1 = Int(ceil(rect.maxY))
  var w = max(0, x1 - x0), h = max(0, y1 - y0)
  if rect.isEmpty || rect.isNull { w = 0; h = 0 }

  var bitmap: [UInt8] = []
  if w > 0 && h > 0 {
    let ctx = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                        space: CGColorSpaceCreateDeviceGray(),
                        bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setFillColor(gray: 0, alpha: 1)
    ctx.fill(CGRect(x: 0, y: 0, width: w, height: h))
    ctx.setAllowsFontSmoothing(false)
    ctx.setShouldSmoothFonts(false)
    ctx.setShouldAntialias(true)
    ctx.setFillColor(gray: 1, alpha: 1)
    var pos = CGPoint(x: -CGFloat(x0), y: -CGFloat(y0))
    CTFontDrawGlyphs(font, &glyph, &pos, 1, ctx)
    let data = ctx.data!.bindMemory(to: UInt8.self, capacity: w * h)
    bitmap = (0..<(w * h)).map { i in
      UInt8((pow(Double(data[i]) / 255.0, gamma) * 255.0).rounded())
    }
  }
  glyphs.append(Glyph(unicode: cp, width: w, height: h, advance: Int(advance.width.rounded()),
                      top: y1, left: x0, bitmap: bitmap))
}

var bytes: [UInt8] = []
func put(_ v: Int) {
  let u = UInt32(bitPattern: Int32(v))
  bytes += [UInt8(u >> 24 & 0xFF), UInt8(u >> 16 & 0xFF), UInt8(u >> 8 & 0xFF), UInt8(u & 0xFF)]
}
put(glyphs.count)
put(11)
put(Int(pixelSize.rounded()))
put(0)
put(Int(CTFontGetAscent(font).rounded()))
put(Int(CTFontGetDescent(font).rounded()))
for g in glyphs {
  put(Int(g.unicode)); put(g.height); put(g.width); put(g.advance); put(g.top); put(g.left); put(0)
}
for g in glyphs { bytes += g.bitmap }

var out = "// Generated by tools/make_vlw_font.swift from \((fontPath as NSString).lastPathComponent) at \(args[2]) px.\n"
out += "// SIL Open Font License 1.1, see assets/fonts/OFL.txt. Do not edit.\n#pragma once\n#include <cstdint>\n\n"
out += "static const uint8_t \(symbol)[\(bytes.count)] = {\n"
for start in stride(from: 0, to: bytes.count, by: 20) {
  let line = bytes[start..<min(start + 20, bytes.count)].map { String(format: "0x%02X", $0) }
  out += "  " + line.joined(separator: ",") + ",\n"
}
out += "};\n"
try! out.write(toFile: outPath, atomically: true, encoding: .utf8)
print("\(symbol): \(glyphs.count) glyphs, \(bytes.count) bytes" + (missing.isEmpty ? "" : ", missing \(missing.joined(separator: " "))"))
